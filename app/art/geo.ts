export type Bounds = { lon0: number; lon1: number; lat0: number; lat1: number; w: number; h: number };

export const WORLD: Bounds = { lon0: -170, lon1: 180, lat0: -50, lat1: 78, w: 1600, h: 585 };
export const INDIA: Bounds = { lon0: 67, lon1: 98, lat0: 5.5, lat1: 37, w: 620, h: 630 };

export const project = (b: Bounds, lon: number, lat: number): [number, number] =>
  [((lon - b.lon0) / (b.lon1 - b.lon0)) * b.w, ((b.lat1 - lat) / (b.lat1 - b.lat0)) * b.h];

function inside([x, y]: [number, number], poly: Poly) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** A single SVG path of zero-length round-capped segments: one dot per land grid point. */
function dotPath(b: Bounds, polys: Poly[], step: number) {
  let d = '';
  for (let lat = b.lat1 - step / 2; lat > b.lat0; lat -= step) {
    // Stagger alternate rows for a woven, less mechanical texture.
    const row = Math.round((b.lat1 - lat) / step);
    for (let lon = b.lon0 + step / 2 + (row % 2 ? step / 2 : 0); lon < b.lon1; lon += step) {
      if (polys.some(p => inside([lon, lat], p))) {
        const [x, y] = project(b, lon, lat);
        d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`;
      }
    }
  }
  return d;
}

